// Authorized read-only projection over the existing `audit` table.
//
// This module never writes and never widens authority: src/admin/router.mjs
// runs requireAdmin(ctx, 'admin.audit.read') BEFORE calling readAudit, so the
// caller is already a live security_reviewer grant holder.
//
// The projection is deliberately narrow. Audit rows are produced by other
// owners (worker.js, lib/store.js, dgm/router.mjs, fabric/*) whose `target`
// and `detail` columns carry identity, fixture labels, node ids, addresses
// and free text. Those columns are never selected. `action` is not a filtered
// free-text field: it is admitted only when it is one of the exact strings
// those writers emit today, because a grammar (or a namespace prefix) check
// still admits arbitrary attacker-chosen suffixes such as
// `resource.synthetic_secret_value`. Anything else is reported as
// action:null / action_known:false / category:"unknown" rather than guessed at.
import { pageQuery } from '../lib/store.js';

export const AUDIT_SCHEMA_VERSION = 'admin.audit.v1';

// Exact audit action vocabulary, derived from the current write sites:
//   src/worker.js            (incl. inline INSERT ... SELECT statements)
//   src/lib/store.js         audit() helper, called from src/worker.js
//   src/dgm/router.mjs       auditInsert(); `dgm.preview.${action}` is bounded
//                            by the route regex to pause|resume|cancel
//   src/fabric/operations.mjs, src/fabric/store.mjs
//                            `fabric.approval.${decision}` is bounded to
//                            approved|rejected by the decision parser
// Adding an action here is a contract change: update
// goose-evidence/admin-audit-20261101/author/INTERFACE.md in the same commit.
